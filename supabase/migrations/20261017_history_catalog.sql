-- Applied to the shared abonnement Supabase project. This educational catalog stores
-- only generic vocabulary definitions and examples, no user IDs or raw transcripts.
create table if not exists public.vocab_history_catalog (
  id bigint generated by default as identity primary key,
  pack_slug text not null,
  normalized_key text not null,
  term text not null check (char_length(trim(term)) between 1 and 150),
  meaning text not null check (char_length(trim(meaning)) between 1 and 500),
  translation_ar text not null default '',
  example text not null default '',
  category text not null default 'Quotidien',
  learned_on date not null,
  source text not null default 'Sélection linguistique',
  created_at timestamptz not null default now(),
  unique(pack_slug,normalized_key)
);
create index if not exists vocab_history_catalog_pack_idx on public.vocab_history_catalog(pack_slug,id);
alter table public.vocab_history_catalog enable row level security;
revoke all on public.vocab_history_catalog from anon,authenticated;
grant select on public.vocab_history_catalog to anon,authenticated;
create policy "Public vocabulary packs are read-only" on public.vocab_history_catalog
  for select to anon,authenticated using (true);
